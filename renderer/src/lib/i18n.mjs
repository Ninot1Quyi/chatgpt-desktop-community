function interpolate(message, variables) {
  if (!variables) return message;
  return message.replace(/\{(\w+)\}/g, (match, key) =>
    Object.prototype.hasOwnProperty.call(variables, key)
      ? String(variables[key])
      : match);
}

const ZH_CN_PATTERNS = Object.freeze([
  [/^Installed for (.+)$/, "已为 $1 安装"],
  [/^Available from (.+)$/, "可从 $1 安装"],
  [/^(.+) CLI was not found\.$/, "未找到 $1 CLI。"],
  [/^No (.+)-compatible package is published for this plugin\.$/, "此插件未发布兼容 $1 的插件包。"],
  [/^This package does not contain a (.+)-compatible manifest or skill\.$/, "此插件包不包含兼容 $1 的清单或技能。"],
  [/^This package only contains capabilities that (.+) cannot install\.$/, "此插件包仅包含 $1 无法安装的能力。"],
]);

function translateZh(message) {
  if (ZH_CN[message]) return ZH_CN[message];
  for (const [pattern, replacement] of ZH_CN_PATTERNS) {
    if (pattern.test(message)) return message.replace(pattern, replacement);
  }
  return message;
}

export function translate(language, message, variables) {
  if (typeof message !== "string") return message;
  const normalized = normalizeLanguage(language);
  const translated = normalized === "zh-CN" ? translateZh(message) : message;
  return interpolate(translated, variables);
}
